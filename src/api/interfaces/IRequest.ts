/**
 * Интерфейсы для работы с HTTP-запросами.
 * Определяют структуру запросов и ответов при взаимодействии с API
 */

/**
 * Интерфейс ответа на HTTP-запрос
 * Описывает структуру данных, возвращаемых после выполнения запроса
 *
 * @template T - Тип данных, ожидаемых в ответе от сервера
 *
 * @example
 * ```ts
 * // Пример использования с типом User
 * interface User {
 *   id: number;
 *   name: string;
 * }
 *
 * const response: IRequestSend<User> = {
 *   status: true,
 *   data: { id: 1, name: "John" }
 * };
 *
 * // Пример обработки ошибки
 * const errorResponse: IRequestSend<User> = {
 *   status: false,
 *   data: null,
 *   err: "User not found"
 * };
 * ```
 */
export interface IRequestSend<T> {
    /**
     * Статус выполнения запроса
     * - true - запрос выполнен успешно
     * - false - произошла ошибка при выполнении запроса
     */
    status: boolean;

    /**
     * Данные, полученные от сервера
     * - null - в случае ошибки или отсутствия данных
     * - T - данные в формате, указанном в типе
     */
    data: T | null;

    /**
     * Ошибка (объект Error либо текст ошибки).
     * Присутствует только в случае неуспешного выполнения запроса (status = false)
     */
    err?: Error | string;

    /**
     * HTTP-статус ответа, если сервер ответил не 2xx. Отсутствует, если ответа не было
     * (таймаут, сетевая ошибка). Нужен, чтобы отличать, например, 429 от 400.
     */
    httpStatus?: number;

    /**
     * Тело ответа сервера со статусом не 2xx (обрезается до 1000 символов).
     * Платформы кладут туда причину отказа и параметры повтора (`retry_after` у Telegram).
     */
    errorBody?: string;
}
